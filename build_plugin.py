#!/usr/bin/env python3
"""把 src/client.js 组装成 DSH 可加载的浏览器 bundle（lib/client.js）。

做三件事：
  1. 注入鲸鱼几何（SEGS / WSEG / STATIC_D / SWING，来自 v4/src/whale_geom.py）
  2. 注入图标路径（来自 v4/svg/icon-*.svg）
  3. 包上 window.__ModuleLoader__.load({ id, factory }) 外壳

本副本是「对话 5」的独立工作拷贝。v4 素材查找顺序：
  1. 环境变量 WHALE_V4 指向的目录
  2. 原开发目录的 ../../v4（本拷贝位于 5-…/插件/dsh-plugin-whale 时不存在）
  3. 同级的 ../build-support/v4（随本拷贝一起保存的素材）
"""
from __future__ import annotations

import json
import os
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent


def find_v4() -> pathlib.Path:
    """按优先级定位 v4 素材目录，找不到就报错退出。"""
    env = os.environ.get("WHALE_V4")
    if env:
        return pathlib.Path(env).expanduser().resolve()
    for cand in (HERE.parents[1] / "v4", HERE.parent / "build-support" / "v4"):
        if (cand / "src" / "whale_geom.py").is_file():
            return cand
    raise SystemExit(
        "找不到 v4 素材目录：请设置 WHALE_V4，或把 build-support/v4 放在 "
        f"{HERE.parent} 下"
    )


V4 = find_v4()
SRC = HERE / "src" / "client.js"
OUT = HERE / "lib" / "client.js"
PKG = "dsh-plugin-whale"

sys.path.insert(0, str(V4 / "src"))
import whale_geom as WG   # noqa: E402


def geometry() -> str:
    js = WG.bend_js(2.2)
    segs = re.search(r"const SEGS = (\[.*?\]);", js, re.S).group(1)
    wseg = re.search(r"const WSEG = (\[.*?\]);", js, re.S).group(1)
    _, static_d = WG.load()
    return (f"const SEGS = {segs};\nconst WSEG = {wseg};\n"
            f"const STATIC_D = {json.dumps(static_d)};\nconst SWING = {WG.SWING};")


def icons() -> str:
    out = {}
    for name, key in (("icon-granary", "granary"), ("icon-bowl-balance", "bowl-balance"),
                      ("icon-bowl-gift", "bowl-gift"), ("icon-bowl-spent", "bowl-spent")):
        svg = (V4 / "svg" / f"{name}.svg").read_text()
        groups = re.findall(r'<g fill="none" stroke="currentColor" stroke-width="([\d.]+)"[^>]*>(.*?)</g>',
                            svg, re.S)
        main, fine = [], []
        for weight, body in groups:
            (fine if weight == "1.1" else main).extend(re.findall(r'd="([^"]+)"', body))
        out[key] = {"main": main, "fine": fine}
    return json.dumps(out, ensure_ascii=False, separators=(",", ":"))


def main() -> None:
    body = SRC.read_text()
    body = body.replace("/*__GEOM__*/", geometry())
    body = body.replace("/*__ICONS__*/{}", icons())

    bundle = (
        "/* dsh-plugin-whale — browser half (generated by build_plugin.py; edit src/client.js) */\n"
        "window.__ModuleLoader__.load({\n"
        f"\tid: {json.dumps(PKG)},\n"
        "\tfactory: (require) => {\n"
        "\t\tvar module = { exports: {} };\n"
        "\t\tvar exports = module.exports;\n"
        f"{body}\n"
        "\t\treturn module.exports;\n"
        "\t}\n"
        "});\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(bundle, encoding="utf-8")
    print(f"built {OUT} ({len(bundle)} bytes)")


if __name__ == "__main__":
    main()
